def normalize_lang(code):
    c = (code or 'de').strip().lower()[:2]
    return c if c in LANGS else 'de'


def t(key, lang='de', **kw):
    lang = normalize_lang(lang)
    s = STRINGS.get(lang, _DE).get(key) or _DE.get(key) or key
    if kw:
        try:
            return s.format(**kw)
        except Exception:
            return s
    return s


def catalog(lang='de'):
    """Alle Schlüssel für die Palette (Fallback DE)."""
    lang = normalize_lang(lang)
    out = dict(_DE)
    out.update(STRINGS.get(lang) or {})
    return out


